"""Generate Android vectors and a notification SVG from shared card geometry."""

from math import cos, pi, radians, sin
from pathlib import Path

RES = Path(__file__).resolve().parents[1] / "app/src/main/res/drawable"
# REUSE-IgnoreStart
ASSET_HEADER = """<!--
SPDX-FileCopyrightText: 2026 Sofie Finnes <sofie+git@finnes.dev>
SPDX-License-Identifier: LicenseRef-All-Rights-Reserved
-->
"""
# REUSE-IgnoreEnd
CENTER_X, CENTER_Y = 54.0, 48.55
ANGLE = radians(-11)
# Launcher and status glyph share the accepted short-tail silhouette.
PIN = "M54,24.55C40.75,24.55 30,35.3 30,48.55C30,60 47,71.5 52.1,76Q54,77.8 55.9,76C61,71.5 78,60 78,48.55C78,35.3 67.25,24.55 54,24.55Z"
MARK_OFFSET_Y = 3.275


def point(x, y):
    x, y = x - CENTER_X, y - CENTER_Y
    return f"{CENTER_X + x * cos(ANGLE) - y * sin(ANGLE):.3f},{CENTER_Y + x * sin(ANGLE) + y * cos(ANGLE):.3f}"


def rect(x, y, width, height, radius):
    return (
        f"M{point(x + radius, y)}L{point(x + width - radius, y)}"
        f"Q{point(x + width, y)} {point(x + width, y + radius)}L{point(x + width, y + height - radius)}"
        f"Q{point(x + width, y + height)} {point(x + width - radius, y + height)}L{point(x + radius, y + height)}"
        f"Q{point(x, y + height)} {point(x, y + height - radius)}L{point(x, y + radius)}"
        f"Q{point(x, y)} {point(x + radius, y)}Z"
    )


def circle(x, y, radius):
    k = 0.55228475 * radius
    return (
        f"M{point(x + radius, y)}C{point(x + radius, y + k)} {point(x + k, y + radius)} {point(x, y + radius)}"
        f"C{point(x - k, y + radius)} {point(x - radius, y + k)} {point(x - radius, y)}"
        f"C{point(x - radius, y - k)} {point(x - k, y - radius)} {point(x, y - radius)}"
        f"C{point(x + k, y - radius)} {point(x + radius, y - k)} {point(x + radius, y)}Z"
    )


def stamp(x, y):
    points = []
    for i in range(32):
        angle = i * pi / 16
        radius = 3.1 * (1 if i % 4 in (1, 2) else 0.82)
        points.append(point(x + radius * cos(angle), y + radius * sin(angle)))
    return "M" + "L".join(points) + "Z"


def path(data, color, alpha=1):
    return f'<path android:fillColor="{color}" android:fillAlpha="{alpha}" android:fillType="evenOdd" android:pathData="{data}" />\n'


def write(name, body, size=108):
    (RES / f"{name}.xml").write_text(f'''<?xml version="1.0" encoding="utf-8"?>
{ASSET_HEADER}
<!-- Generated by tools/generate_icons.py; shared geometry keeps the card and stamps aligned. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="{size}dp" android:height="{size}dp"
    android:viewportWidth="108" android:viewportHeight="108">
{body}</vector>
''')


CARD = rect(29, 33.55, 50, 30, 5)
INNER = rect(31, 35.55, 46, 26, 3)
CUTOUT = rect(27.7, 32.25, 52.6, 32.6, 6.3)
HEADING = rect(35, 38.55, 12, 1.8, 0.9)
STAMPS = stamp(43.5, CENTER_Y) + stamp(54, CENTER_Y)
EMPTY_STAMP = circle(64.5, CENTER_Y, 2.5) + circle(64.5, CENTER_Y, 1.5)

# The bright ivory card leads; the hot-pink pin frames it against midnight.
ivory_card = f'''<path android:pathData="{CARD}">
    <aapt:attr name="android:fillColor">
        <gradient android:type="linear" android:startX="32" android:startY="31"
            android:endX="78" android:endY="66"
            android:startColor="#FFFDF4" android:endColor="#F7E8CE" />
    </aapt:attr>
</path>
'''
body = path(PIN, "#FF5DAD")
body += path(rect(29.7, 34.75, 50, 30, 5), "#A33B6E", 0.5)
body += ivory_card
body += path(CARD + rect(29.65, 34.2, 48.7, 28.7, 4.35), "#FFFFFF", 0.18)
body += path(HEADING + STAMPS + EMPTY_STAMP, "#482044")
# Recenter the whole mark so shortening the tail cannot misalign the card.
write(
    "ic_launcher_foreground",
    f'<group android:translateY="{MARK_OFFSET_Y}">\n' + body + "</group>\n",
)

# A plain outer silhouette clip contains the oversized subtraction. The void
# itself is still a compound path, avoiding inverse clip-rule differences.
mono = '<group><clip-path android:pathData="' + PIN + '" />\n'
mono += path(PIN + CUTOUT, "#FFFFFF") + "</group>\n" + path(CARD + INNER, "#FFFFFF")
mono += path(HEADING + STAMPS + EMPTY_STAMP, "#FFFFFF")
write(
    "ic_launcher_monochrome",
    f'<group android:translateY="{MARK_OFFSET_Y}">\n' + mono + "</group>\n",
)

# At status-bar sizes, fine outlines and hollow stamps disappear. Keep the
# logo's oversized card silhouette, but give its border and three solid stamps
# enough weight to survive rasterization. Omit the tiny printed heading.
notification_cutout = rect(26.5, 31.05, 55, 35, 7.5)
notification = '<group><clip-path android:pathData="' + PIN + '" />\n'
notification += path(PIN + notification_cutout, "#FFFFFF") + "</group>\n"
notification += path(CARD + rect(33, 37.55, 42, 22, 1), "#FFFFFF")
notification += path("".join(circle(x, CENTER_Y, 3.4) for x in (43.5, 54, 64.5)), "#FFFFFF")
write(
    "ic_card",
    '<group android:scaleX="1.6" android:scaleY="1.6" android:pivotX="54" android:pivotY="54">\n'
    + f'<group android:translateY="{MARK_OFFSET_Y}">\n'
    + notification
    + "</group></group>\n",
    24,
)

(RES / "ic_launcher_background.xml").write_text(f"""<?xml version="1.0" encoding="utf-8"?>
{ASSET_HEADER}
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <solid android:color="#211D47" />
</shape>
""")

# Keep an editable, platform-independent copy of the notification geometry.
DOC_ASSETS = RES.parents[4] / "docs/assets"
(DOC_ASSETS / "notification-icon-native.svg").write_text(f'''{ASSET_HEADER}
<svg xmlns="http://www.w3.org/2000/svg" width="108" height="108" viewBox="0 0 108 108"
    role="img" aria-labelledby="title">
  <title id="title">Portemoné notification icon</title>
  <defs><clipPath id="pin"><path d="{PIN}" /></clipPath></defs>
  <g fill="#FFFFFF" fill-rule="evenodd" transform="translate(54 54) scale(1.6) translate(-54 -54)">
    <g transform="translate(0 {MARK_OFFSET_Y})">
      <g clip-path="url(#pin)"><path d="{PIN + notification_cutout}" /></g>
      <path d="{CARD + rect(33, 37.55, 42, 22, 1)}" />
      <path d="{"".join(circle(x, CENTER_Y, 3.4) for x in (43.5, 54, 64.5))}" />
    </g>
  </g>
</svg>
''')
